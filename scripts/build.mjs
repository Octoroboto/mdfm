// Zero-dependency build: stitches src/ into dist/mdfm.mjs (ES module) and dist/mdfm.iife.js (window.MDFM).
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
const root = new URL("../", import.meta.url);
const read = p => readFileSync(new URL(p, root), "utf8");
const { version } = JSON.parse(read("package.json"));
const pack = read("src/content/default.js").replace(/export default\s*/, "const corePack = ");
const engine = read("src/engine.js").replace(/^import .*$/m, "").replace('"__VERSION__"', JSON.stringify(version)).replace(/^export (const|function) /gm, "$1 ");
const ui = read("src/ui.js").replace(/^export function /m, "function ");
if (/^\s*(import|export)\b/m.test(pack + engine + ui)) throw new Error("build: unexpected import/export left in src; update scripts/build.mjs");
const body = `${pack}\n${engine}\n${ui}\n`;
const banner = `/* MDFM ${version}: generated by "npm run build" from src/. Edit src/, not this file. */\n`;
mkdirSync(new URL("dist/", root), { recursive: true });
writeFileSync(new URL("dist/mdfm.mjs", root), `${banner}${body}export { createMDFM, mountEQ, corePack, VERSION, STYLES };\n`);
writeFileSync(new URL("dist/mdfm.iife.js", root), `${banner}var MDFM = (function () {\n"use strict";\n${body}return { createMDFM, mountEQ, corePack, VERSION, STYLES };\n})();\n`);
console.log(`built mdfm ${version} -> dist/mdfm.mjs, dist/mdfm.iife.js`);
